# ------------------------------------------------------------------ 路径

@dataclass(frozen=True)
class PathSegment:
    """路径的一段(原胞倒数分数坐标)。"""
    start: np.ndarray        # (3,)
    end: np.ndarray          # (3,)
    start_label: str
    end_label: str


@dataclass(frozen=True)
class BandPath:
    """一条 k 路径(原胞分数坐标)。

    采样口径与 vaspkit 一致: **每段采 ``n_points_per_segment`` 个点(含两端)**,
    段与段之间**不共享**点 —— 交界点出现两次(服务器实测的 vaspkit 路径:
    3 段 x 30 点 -> 90 个 k 点, MOMENTUM.grd 的距离序列里交界点的距离出现两次)。
    """
    segments: Tuple[PathSegment, ...]
    k_prim: np.ndarray                       # (n_k, 3) 原胞分数坐标
    n_points_per_segment: int

    @property
    def n_k(self) -> int:
        return int(self.k_prim.shape[0])


def read_kpath(path: str) -> BandPath:
    """读 vaspkit 的 ``KPATH.in`` -> BandPath。

    格式(服务器实测)::

        K-Path Generated by VASPKIT.
           30                     <- 每段的采样点数
        Line-Mode
        Reciprocal
         0.5000000000   0.0000000000   0.0000000000     M      <- 起点 + 标签
         0.0000000000   0.0000000000   0.0000000000     GAMMA  <- 终点 + 标签
        (空行分隔下一段)

    解析刻意宽松: 表头/模式行/空行一律跳过, 只认"3 个浮点数"的数据行, 并按
    **两行一段**配对。标签缺省时用 vaspkit 的 ``XX``。
    """
    with open(path, encoding="utf-8", errors="replace") as fh:
        lines = fh.read().splitlines()
    n_points: Optional[int] = None
    endpoints: List[Tuple[np.ndarray, str]] = []
    for raw in lines:
        s = raw.strip()
        if not s:
            continue
        parts = s.split()
        if n_points is None and len(parts) == 1:
            try:
                n_points = int(parts[0])
            except ValueError:
                pass
            if n_points is not None:
                continue
        if len(parts) < 3:
            continue
        try:
            xyz = np.array([float(x) for x in parts[:3]], dtype=float)
        except ValueError:
            continue                      # 表头/模式行
        label = parts[3].strip() if len(parts) > 3 else "XX"
        endpoints.append((xyz, label))
    if n_points is None:
        raise ValueError(
            f"{os.path.basename(path)} 里没有找到每段的采样点数"
            "(第 2 行应是一个整数)")
    if n_points < 2:
        raise ValueError(
            f"{os.path.basename(path)} 的每段采样点数 = {n_points} < 2 —— "
            "一段至少要有起点与终点两个点")
    if len(endpoints) < 2 or len(endpoints) % 2 != 0:
        raise ValueError(
            f"{os.path.basename(path)} 的路径点不是成对的(读到 "
            f"{len(endpoints)} 个坐标行) —— 格式应为每段两行(起点 + 终点)")
    segments: List[PathSegment] = []
    for i in range(0, len(endpoints), 2):
        start, start_label = endpoints[i]
        end, end_label = endpoints[i + 1]
        segments.append(PathSegment(start, end, start_label, end_label))
    sampled: List[np.ndarray] = []
    t = np.linspace(0.0, 1.0, n_points)
    for seg in segments:
        sampled.append(seg.start[None, :] + t[:, None] * (seg.end - seg.start)[None, :])
    k_prim = np.vstack(sampled)
    return BandPath(tuple(segments), k_prim, n_points)


def path_distances(path: BandPath, b_prim: np.ndarray) -> np.ndarray:
    """沿路径的累计距离(用**原胞**倒格矢; 单位与 b_prim 相同, 2π/Å)。

    段与段的交界点出现两次 ⇒ 该处的步长为 0, 距离自然连续 ✓。
    """
    cart = np.asarray(path.k_prim, dtype=float) @ np.asarray(b_prim, dtype=float)
    step = np.linalg.norm(np.diff(cart, axis=0), axis=1)
    return np.concatenate([[0.0], np.cumsum(step)])


def path_labels(path: BandPath, distances: np.ndarray
                ) -> List[Tuple[str, float]]:
    """高对称点的 (标签, 距离) 列表。

    规则(与 vaspkit 实测一致): 段内两端同名时只写一次, 不同时写
    ``"前一段的终点|后一段的起点"``。
    服务器实测: 3 段 M->GAMMA, GAMMA->M, GAMMA->A ⇒ M / GAMMA / M|GAMMA / A。
    """
    dist = np.asarray(distances, dtype=float)
    n = path.n_points_per_segment
    labels: List[Tuple[str, float]] = [(path.segments[0].start_label, dist[0])]
    for i in range(1, len(path.segments)):
        end_label = path.segments[i - 1].end_label
        start_label = path.segments[i].start_label
        label = end_label if end_label == start_label else f"{end_label}|{start_label}"
        labels.append((label, dist[i * n - 1]))
    labels.append((path.segments[-1].end_label, dist[-1]))
    return labels


def path_to_super_k(k_prim: np.ndarray, m_eff: np.ndarray) -> np.ndarray:
    """原胞分数坐标 -> 超胞分数坐标: ``K = k'·Mᵀ (mod 1)``。

    与 ``geometry.Transform.super_from_prim`` 同一约定(行向量 + 倒空间用 M^-T
    的逆变换)。**转置不能错**: 一般 M 下 ``k'·M`` 与 ``k'·Mᵀ`` 给的是不同的 k。
    """
    m = np.asarray(m_eff, dtype=float)
    k = np.asarray(k_prim, dtype=float)
    return np.mod(k @ m.T, 1.0)


# ------------------------------------------------------------------ 写出

def dedup_k_points(k_super: np.ndarray, tol: float = KPOINT_DEDUP_TOL
                   ) -> Tuple[np.ndarray, np.ndarray]:
    """按**周期距离**去重超胞 k 点 -> (去重后的 k, 每个输入点对应的行号)。

    **为什么必须去重**: VASP 6.6.0 读到含**重复 k 点**的显式列表会崩
    (服务器实测 2026-11-18: 控制器连续四次用 `unfoldfs band` 生成的 KPOINTS
    跑 VASP, 每次都在第一个 k 点算完后死掉 —— OUTCAR 停在
    "writing wavefunctions", EIGENVAL 里只有 1 个 k 点; 手工去重并把表头
    计数改成 33 之后, 同一次计算 194 s 跑完全部 33 个 k 点 ✓)。

    重复的来源有**两个**:
      1. 路径的**相邻段共享端点**(M 既是第 1 段的终点又是第 2 段的起点);
      2. **折叠**到超胞后重合(不同的原胞 k 折到同一个超胞 k —— 这不是重复
         计算, 而是同一个超胞 k 只算一次, 展开时再各自取自己的候选)。

    判定用**周期距离**(分数坐标, 容差 1e-6)⇒ 0.9999999999 与 0.0 是同一个点。
    行序 = **首次出现顺序** ⇒ 路径的前几个点仍是前几个点(相位约定择优的
    采样口径依赖这一点)。
    """
    k = np.atleast_2d(np.asarray(k_super, dtype=float))
    keep: List[np.ndarray] = []
    index = np.empty(k.shape[0], dtype=int)
    for i in range(k.shape[0]):
        if keep:
            d = periodic_distance(k[i][None, :], np.array(keep))[0]
            j = int(np.argmin(d))
            if float(d[j]) <= tol:
                index[i] = j
                continue
        index[i] = len(keep)
        keep.append(k[i])
    unique = (np.array(keep, dtype=float) if keep
              else np.zeros((0, 3), dtype=float))
    return unique, index


def write_kpoints_explicit(path: str, k_super: np.ndarray) -> None:
    """写"显式 k 点列表"格式的 KPOINTS。

    首行是**纯注释**(以 'u' 开头)—— VASP 按首行的**第一个字符**选解析分支,
    'G'/'M' 会走"自动生成网格"分支(此时显式列表被忽略, k 点的个数与顺序都变)。
    该首行格式的事实来源是 ``grid.write_kpoints(..., explicit=True)``;
    这里照抄它的布局(注释首行 + 点数 + "Reciprocal lattice" + 每行
    ``kx ky kz weight``), 不另起炉灶。

    ⚠ **写出的 k 点按周期距离去重**(见 ``dedup_k_points``): VASP 6.6.0 读到
    含重复 k 点的显式列表会崩(服务器实测)。表头的 k 点计数 = **实际写出的
    行数**(去重后的数量)✓。
    """
    k, _index = dedup_k_points(k_super)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(f"unfoldfs: explicit k-point list (do not edit) -- "
                 f"band path, {k.shape[0]} points\n")
        fh.write(f"   {k.shape[0]}\n")
        fh.write("Reciprocal lattice\n")
        for row in k:
            fh.write(f"    {row[0]:.12f}    {row[1]:.12f}    {row[2]:.12f}    "
                     f"1.000000000000\n")


def write_grd(path: str, matrix: np.ndarray) -> None:
    """写 vaspkit 的 .grd(每行一条带, 每列一个 k 点; 字段宽 14)。"""
    mat = np.atleast_2d(np.asarray(matrix, dtype=float))
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        for row in mat:
            fh.write("".join(f"{v:{GRD_FIELD_WIDTH}.6f}" for v in row) + "\n")


def write_klabels(path: str, labels: Sequence[Tuple[str, float]]) -> None:
    """写 KLABELS(表头 + 标签行 + 2 行空白 + vaspkit 的提示行)。

    标签**右对齐**在 12 列: MATLAB 的 ``regexp(str, '\\s+', 'split')`` 会把
    前导空白切成第一个空字段, 只有右对齐时 ``S(2)`` 才是标签。
    """
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(KLABELS_HEADER + "\n")
        for label, dist in labels:
            fh.write(f"{label:>12}{float(dist):>12.3f}\n")
        fh.write(" \n")
        fh.write(" \n")
        fh.write(KLABELS_TIP + "\n")


def read_klabels(path: str) -> List[Tuple[str, float]]:
    """读回 KLABELS(阶段 2 用它核对阶段 1 的记录) -> [(标签, 距离), ...]。

    按 MATLAB 的口径跳过表头、两行空白与提示行, 只留标签行。
    """
    with open(path, encoding="utf-8", errors="replace") as fh:
        lines = fh.read().splitlines()
    out: List[Tuple[str, float]] = []
    for line in lines:
        s = line.strip()
        if not s or s == " " or s.startswith("K-Label") or s.startswith("* Tip"):
            continue
        parts = s.split()
        if len(parts) < 2:
            continue
        out.append((parts[0], float(parts[1])))
    return out


def write_band_dat(path: str, distances: np.ndarray, energies: np.ndarray,
                   weights: np.ndarray) -> None:
    """写长表 ``unfolded_band.dat``: 每行 = 路径距离 / E(eV) / 权重 / 带号。

    这是**自用**的格式(方便二次分析), 不是 vaspkit 的格式。
    """
    dist = np.asarray(distances, dtype=float)
    energy = np.atleast_2d(np.asarray(energies, dtype=float))
    weight = np.atleast_2d(np.asarray(weights, dtype=float))
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("# 路径距离(2π/Å)  E(eV, 绝对值)  权重  带号\n")
        for b in range(energy.shape[0]):
            for j in range(energy.shape[1]):
                fh.write(f"{dist[j]:.10f} {energy[b, j]:.10f} "
                         f"{weight[b, j]:.10f} {b + 1}\n")


# ------------------------------------------------------------------ 组装

def select_zero_candidate(k_cand: np.ndarray, k_prim_point: np.ndarray,
                          tol: float = CANDIDATE_TOL) -> int:
    """在候选原胞 k 里找出"原胞 k 等于该路径点"的那个候选。

    候选 k_cand[j] = (K + G_j)·M^-ᵀ, 落在原胞第一布里渊区 [0,1)³。路径点
    k'_i (mod 1) 一定落在其中某一个上(与 K = k'·Mᵀ 一致时就是 G=0 的那个)⇒
    用**周期距离**匹配, 容差 1e-6。

    匹配不到必须**报错**: 静默取最近的候选会把别的原胞 k 的谱当成这条路径点的
    谱(能带形状整个错掉, 而且看不出来)。
    """
    d = periodic_distance(np.atleast_2d(np.asarray(k_prim_point, dtype=float)),
                          np.atleast_2d(np.asarray(k_cand, dtype=float)))[0]
    j = int(np.argmin(d))
    if float(d[j]) > tol:
        raise ValueError(
            f"路径点 {np.asarray(k_prim_point, dtype=float).tolist()} 在展开结果里"
            f"找不到对应的候选(最近的候选周期距离 {float(d[j]):.3e} > {tol:.0e}) —— "
            "候选原胞 k 与路径不自洽; 请确认 KPOINTS 是本工具写的、且 INCAR 里 "
            "ISYM = 0")
    return j


def assemble_band(unfolded, k_prim: np.ndarray, tol: float = CANDIDATE_TOL,
                  *, index_map: Optional[np.ndarray] = None
                  ) -> Tuple[np.ndarray, np.ndarray]:
    """把展开结果组装成 (n_band, n_k) 的能带与权重矩阵。

    每个路径点取"原胞 k 等于该路径点"的候选(见 ``select_zero_candidate``),
    候选内的带按能量升序。**各路径点的带数可能不同**(展开把态摊到不同候选上),
    故取全路径的最大值作为行数, 不足的行用"该 k 的最高带能量 + 权重 0"补位 ——
    权重 0 ⇒ 在加权图里不显色。

    ``index_map``: 路径点 -> 展开结果的行号(``dedup_k_points`` 给出的映射)。
    **路径点可以比计算的 k 点多**: 路径的相邻段共享端点(同一个 k 算一次),
    且不同的原胞 k 可能折到同一个超胞 k ⇒ 多个路径点映射到**同一个**已计算的
    k, 各自再取自己的候选(同一个超胞 k 的不同 G)。缺省时是恒等映射(每个
    路径点对应展开结果的一行)。
    """
    k_prim = np.atleast_2d(np.asarray(k_prim, dtype=float))
    n_path = k_prim.shape[0]
    if index_map is None:
        index_map = np.arange(n_path)
    index_map = np.asarray(index_map, dtype=int)
    if index_map.shape != (n_path,):
        raise ValueError(
            f"index_map 的长度 {index_map.shape[0]} != 路径点数 {n_path}")
    n_calc = int(unfolded.k_cand.shape[0])
    n_used = int(index_map.max()) + 1 if n_path else 0
    if n_calc != n_used:
        raise ValueError(
            f"展开结果的 k 点数 {n_calc} != 路径点映射到的计算 k 点数 {n_used}")
    per_k: List[Tuple[np.ndarray, np.ndarray]] = []
    for i in range(n_path):
        row = int(index_map[i])
        j = select_zero_candidate(unfolded.k_cand[row], k_prim[i], tol)
        valid = unfolded.valid[row, j]
        e = np.asarray(unfolded.energies[row, j], dtype=float)[valid]
        w = np.asarray(unfolded.weights[row, j], dtype=float)[valid]
        per_k.append((e, w))
    n_band = max((e.size for e, _ in per_k), default=0)
    if n_band == 0:
        raise ValueError("所有路径点的候选里都没有有效的带 —— 展开结果为空")
    energies = np.zeros((n_band, n_path))
    weights = np.zeros((n_band, n_path))
    for i, (e, w) in enumerate(per_k):
        m = int(e.size)
        energies[:m, i] = e
        weights[:m, i] = w
        if m < n_band:
            energies[m:, i] = e[-1] if m else 0.0
            weights[m:, i] = 0.0
    return energies, weights


def _path_orbits(k_prim: np.ndarray, ops: SymmetryOps,
                 tol: float = CANDIDATE_TOL) -> List[np.ndarray]:
    """把**路径上的**k 点按点群轨道分组(只保留也在路径上的成员)。

    轨道成员 = 用 ops 的每个操作把点 i 映出去后, 落在**路径上**的那些点
    (周期距离 <= tol)。泛路径点的轨道通常**离开**路径 ⇒ 只有一个成员
    (即无操作) —— 这是"只在路径上做对称化"的必然结果, 见
    docs/algorithms.md §16.7。
    """
    k = np.mod(np.atleast_2d(np.asarray(k_prim, dtype=float)), 1.0)
    n = int(k.shape[0])
    n_ops = int(ops.rotations.shape[0])
    match = np.empty((n, n_ops), dtype=int)
    for o in range(n_ops):
        img = ops.apply(k, o)                     # (n,3) 每个路径点的对称像
        d = periodic_distance(k, img)             # (n,n) 像 -> 路径上的点
        j = d.argmin(axis=1)
        best = d[np.arange(n), j]
        match[:, o] = np.where(best <= tol, j, -1)
    seen = np.zeros(n, dtype=bool)
    orbits: List[np.ndarray] = []
    for i in range(n):
        if seen[i]:
            continue
        members = {i}
        for o in range(n_ops):
            j = int(match[i, o])
            if j >= 0:
                members.add(j)
        idx = np.array(sorted(members), dtype=int)
        seen[idx] = True
        orbits.append(idx)
    return orbits


def symmetrize_band_weights(energies: np.ndarray, weights: np.ndarray,
                            k_prim: np.ndarray, ops: SymmetryOps, *,
                            tol: float = CANDIDATE_TOL,
                            e_tol: float = 1e-3) -> np.ndarray:
    """按点群轨道(限制在**路径上**的成员)平均展开谱权重(修复轮 5)。

    展开谱权重在晶体点群下**不协变**(机制见 docs/algorithms.md §15), 于是
    路径上**对称相关**的两点会给出不同的权重(同一段路径的两半颜色不同)。
    这里把同一轨道上的权重取平均 —— 与 ``expand.symmetrize_spectral_function``
    对费米面做的事同源, 只是对象是路径上的**权重矩阵**而不是 A(k,E)。

    参数
    ----
    energies : (n_band, n_k) 带能量(eV), 行 = 带、列 = 路径点
    weights  : (n_band, n_k) 带权重
    k_prim   : (n_k, 3) 路径点的原胞分数坐标
    ops      : 对称操作(CLI 传的是**原胞完整点群** —— 见
               ``geometry.primitive_symmetry_ops`` 与 docs/algorithms.md §15.8:
               破坏对称性的超胞只保留 4/12 个公共操作, 用公共子群会漏掉路径上
               其余的对称相关点)
    e_tol    : 带能量的匹配容差(eV) —— 只有**各成员同一行的带能量彼此相符**
               时才平均(否则那两行根本不是同一条带, 平均会把不同的带混起来)

    返回
    ----
    与 ``weights`` 同形状的新数组。

    ⚠ **通常是无操作**: 泛路径点的点群轨道**离开**路径 ⇒ 没有可比较的伙伴。
    只有当路径**同时经过**对称相关的点(例如路径上出现 k 与 R·k)时才会生效。
    ⚠ **只动权重, 不动能量**: 带能量本来就是对称的(对称相关点吻合 8e-6 eV)。
    """
    e = np.atleast_2d(np.asarray(energies, dtype=float))
    w = np.atleast_2d(np.asarray(weights, dtype=float))
    if e.shape != w.shape:
        raise ValueError(f"energies 的形状 {e.shape} != weights 的形状 {w.shape}")
    k = np.atleast_2d(np.asarray(k_prim, dtype=float))
    if int(e.shape[1]) != int(k.shape[0]):
        raise ValueError(
            f"路径点数 {k.shape[0]} != 权重矩阵的列数 {e.shape[1]}")
    out = np.array(w, dtype=float, copy=True)
    for members in _path_orbits(k, ops, tol=tol):
        if members.size < 2:
            continue
        sub_e = e[:, members]
        sub_w = w[:, members]
        # 逐行判定: 这一行在各成员上是不是**同一条带**(能量与参考成员相符)?
        same_band = np.all(np.abs(sub_e - sub_e[:, 0:1]) <= e_tol, axis=1)
        if not same_band.any():
            continue
        mean = sub_w[same_band].mean(axis=1)
        for m in members:
            out[same_band, m] = mean
    return out


def mirror_path(distances: np.ndarray, energies: np.ndarray, weights: np.ndarray
                ) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """镜像路径: 路径反过来走, 距离取负(与 MATLAB 脚本的 IsPlotMirror 一致)。"""
    d = -np.asarray(distances, dtype=float)[::-1]
    e = np.atleast_2d(np.asarray(energies, dtype=float))[:, ::-1]
    w = np.atleast_2d(np.asarray(weights, dtype=float))[:, ::-1]
    return d, e, w


