def _band_figure_colors(weight: np.ndarray, scale: str = "linear") -> np.ndarray:
    """把 (n_band, n_k) 的权重矩阵变成 0~1 的颜色值(按行优先展平)。

    * ``linear``：``w / max(w)``（全局）—— 原来的做法；
    * ``log``：``log10(w)`` 在 ``[w_min⁺, w_max]`` 上线性映射到 0~1（w = 0 -> 0）。

    为什么要 ``log``：权重是**投影量**, 绝对值在不同带之间可以差两个量级
    （实测 1T-TaS₂ 的 3×1×1 展开能带：+10.8 eV 那条强局域平带 w = 9.23，
    而 E_F 附近的带只有 0.26~1.12）⇒ 全局线性色标会把 E_F 附近压到
    色标的 3%~12% ⇒ 图上"看不到权重"。

    """
    w = np.asarray(weight, dtype=float)
    if scale not in ("linear", "log"):
        raise ValueError(
            f"weight_scale 只能是 'linear' 或 'log', 给出 {scale!r}")
    flat = w.ravel()
    if flat.size == 0:
        return np.zeros(0)
    if scale == "linear":
        wmax = float(np.max(flat))
        if wmax <= 0:
            return np.zeros(flat.size)
        return flat / wmax
    pos = flat[flat > 0]
    if pos.size == 0:
        return np.zeros(flat.size)
    wmax = float(np.max(pos))
    wmin = float(np.min(pos))
    if wmax <= wmin:                     # 只有一个非零值 => 它就是满格
        return np.where(flat > 0, 1.0, 0.0)
    lo, hi = np.log10(wmin), np.log10(wmax)
    out = np.zeros(flat.size)
    m = flat > 0
    out[m] = (np.log10(flat[m]) - lo) / (hi - lo)
    return out


def weight_scale_is_skewed(weight: np.ndarray, factor: float = 30.0) -> bool:
    """权重是否跨了 1.5 个量级以上（=> 全局线性色标会把大多数带压成深蓝）。

    判据：``max(w) / median(w>0) >= factor``。实测 1T-TaS₂：3×1×1 展开能带
    **175.6**、原胞直通 **76.2**（都会触发提醒）；量级相近的常规情形不会。
    """
    w = np.asarray(weight, dtype=float)
    pos = w[w > 0]
    if pos.size == 0:
        return False
    return float(np.max(pos)) / float(np.median(pos)) >= factor


def band_spectral_function(distances: np.ndarray, energies: np.ndarray,
                           weights: np.ndarray, e_grid: np.ndarray,
                           sigma: float) -> np.ndarray:
    """沿 k 路径的**谱函数** A(k,E) = Σ_b w_b(k)·exp(−(E−E_b(k))²/2σ²)。

    返回 (n_E, n_k)。这是"热图风格"的展开能带图画的东西：x = 路径距离,
    y = 能量, 颜色 = 谱权重（与网格模式 `unfold` 的 A(k,E) 同一个定义 ✓）。

    ``energies`` / ``weights`` 是 (n_band, n_k)；带数不足的行(补位槽)按
    能量 0、权重 0 处理 ⇒ 不贡献 ✓。
    """
    e = np.atleast_1d(np.asarray(e_grid, dtype=float))
    en = np.atleast_2d(np.asarray(energies, dtype=float))
    w = np.atleast_2d(np.asarray(weights, dtype=float))
    if en.shape != w.shape:
        raise ValueError(f"energies {en.shape} 与 weights {w.shape} 形状不一致")
    sigma = float(sigma)
    if not sigma > 0.0:
        raise ValueError(f"sigma 必须为正, 给出 {sigma}")
    valid = np.isfinite(en)
    en = np.where(valid, en, 0.0)
    w = np.where(valid, w, 0.0)
    out = np.zeros((e.size, en.shape[1]))
    for j in range(en.shape[1]):
        d = e[:, None] - en[:, j][None, :]
        out[:, j] = (np.exp(-d * d / (2.0 * sigma * sigma))
                     * w[:, j][None, :]).sum(axis=1)
    return out


def plot_band(distances: np.ndarray, energies: np.ndarray, weights: np.ndarray,
              labels: Sequence[Tuple[str, float]], e_f: float,
              out_path: str, e_min: Optional[float] = None,
              e_max: Optional[float] = None, mirror: bool = False,
              weight_scale: str = "linear", style: str = "line") -> str:
    """画 E-vs-路径距离 的加权能带图, 存成 PNG。

    画图本身在 ``_band_figure``（线图）/ ``_band_heatmap_figure``（热图）,
    图注在 ``plot_caption``。
    ``weight_scale``: ``linear``（全局 w/w_max）或 ``log``（见
    ``_band_figure_colors``）。
    ``style``: ``line``（带线 + 顶部色条）或 ``heatmap``（A(k,E) 热图 +
    底部色条, 与用户的参考截图同款）。
    """
    _require_matplotlib()
    import matplotlib.pyplot as plt
    if style == "heatmap":
        fig, _ax = _band_heatmap_figure(distances, energies, weights, labels,
                                         e_f, e_min=e_min, e_max=e_max,
                                         mirror=mirror,
                                         weight_scale=weight_scale)
    elif style == "line":
        fig, _ax = _band_figure(distances, energies, weights, labels, e_f,
                                 e_min=e_min, e_max=e_max, mirror=mirror,
                                 weight_scale=weight_scale)
    else:
        raise ValueError(f"style 只能是 'line' 或 'heatmap', 给出 {style!r}")
    fig.savefig(out_path, dpi=300)
    plt.close(fig)
    return out_path


def plot_caption(e_f: float, e_lo: float, e_hi: float) -> str:
    """图注: 费米能与**画出来的**能量窗口(eV)。

    ``e_lo`` / ``e_hi`` = 画布上的 y 轴范围(= ``--e-min`` / ``--e-max``,
    没给时是数据的极值)⇒ 读者不用猜图上到底画了哪一段能量。
    """
    return (f"E_F = {float(e_f):.6f} eV; "
            f"E_plot = [{float(e_lo):.3f}, {float(e_hi):.3f}] eV")


def _band_figure(distances: np.ndarray, energies: np.ndarray,
                 weights: np.ndarray, labels: Sequence[Tuple[str, float]],
                 e_f: float, e_min: Optional[float] = None,
                 e_max: Optional[float] = None, mirror: bool = False,
                 weight_scale: str = "linear"):
    """画 E-vs-路径距离 的加权能带图 -> (fig, ax)。

    * 按权重着色(jet, 与 MATLAB 脚本的 ``colormap('jet')`` 同风格)并用线宽
      体现权重;
    * E_F 处画水平虚线, 并在图上标出 E_F 的**数值**(修复轮 7 / B3);
    * 高对称点处画竖线与标签;
    * 图注写明**画出来的**能量窗口(E_plot_min / E_plot_max)(同上);
    * x 轴的单位是 **2π/Å**(与 ``MOMENTUM.grd`` / ``KLABELS`` 一致;
      修复轮 7 / B2 —— 旧实现写的是 "1/Angstrom", 与本工具其它输出矛盾);
    * ``mirror=True`` 时把镜像路径(距离取负、顺序反过来)也画上;
    * ``weight_scale``: ``linear``（全局 w/w_max）或 ``log``（见
      ``_band_figure_colors`` —— 权重跨量级时用 log 才看得到颜色）。
    """
    _require_matplotlib()
    import matplotlib.pyplot as plt
    from matplotlib.cm import ScalarMappable
    from matplotlib.collections import LineCollection
    from matplotlib.colors import Normalize

    dist = np.asarray(distances, dtype=float)
    energy = np.atleast_2d(np.asarray(energies, dtype=float))
    weight = np.atleast_2d(np.asarray(weights, dtype=float))

    def _segments(d: np.ndarray, e: np.ndarray, w: np.ndarray):
        segs, cols = [], []
        # 颜色按**点**算(与 _band_figure_colors 同一口径), 段上取两端平均
        pt = _band_figure_colors(w, weight_scale).reshape(w.shape)
        for b in range(e.shape[0]):
            for j in range(e.shape[1] - 1):
                segs.append([(d[j], e[b, j]), (d[j + 1], e[b, j + 1])])
                cols.append(0.5 * (pt[b, j] + pt[b, j + 1]))
        return segs, cols

    fig, ax = plt.subplots(figsize=(6.0, 4.5))
    cmap = plt.get_cmap("jet")
    groups = [(dist, energy, weight)]
    if mirror:
        groups.append(mirror_path(dist, energy, weight))
    for d, e, w in groups:
        segs, cols = _segments(d, e, w)
        if not segs:
            continue
        lc = LineCollection(segs, cmap=cmap, linewidths=1.2, zorder=2)
        lc.set_array(np.array(cols))
        ax.add_collection(lc)
        lw = 0.4 + 1.8 * np.array(cols)
        lc.set_linewidth(lw)
    lo = e_min if e_min is not None else float(np.min(energy))
    hi = e_max if e_max is not None else float(np.max(energy))
    ax.set_ylim(lo, hi)
    # x 轴范围要覆盖镜像路径(距离取负)—— 否则镜像那一半会被裁掉
    x_lo = min(float(np.min(d)) for d, _e, _w in groups)
    x_hi = max(float(np.max(d)) for d, _e, _w in groups)
    ax.set_xlim(x_lo, x_hi)
    if np.isfinite(e_f):
        ax.axhline(float(e_f), color="k", linestyle="--", linewidth=0.8, zorder=3)
        if lo <= float(e_f) <= hi:
            ax.text(0.995, float(e_f), f"E_F = {float(e_f):.6f} eV",
                    transform=ax.get_yaxis_transform(), ha="right", va="bottom",
                    fontsize=8, color="k", zorder=4)
    for label, d in labels:
        ax.axvline(float(d), color="0.6", linewidth=0.6, zorder=1)
    if mirror:
        for label, d in labels:
            ax.axvline(-float(d), color="0.6", linewidth=0.6, zorder=1)
    ax.set_xlabel(K_PATH_AXIS_LABEL)
    ax.set_ylabel("Energy (eV)")
    # 顶部横向 colorbar(用户参考截图的样式: 左 Low / 右 High, jet, 无刻度)。
    # 布局自上而下: 高对称点标签行 -> colorbar 行 -> 能带曲线区。
    # 色条与标签的位置都依赖主轴的最终位置 => 必须等 tight_layout 之后再算。
    # 右侧留 8% 给色条右端的 "High"(否则它会被画布边缘裁掉)。
    fig.tight_layout(rect=(0.0, 0.06, 0.92, 0.86))
    pos = ax.get_position()
    cax = fig.add_axes([pos.x0, pos.y1 + 0.040, pos.width, 0.018])
    sm = ScalarMappable(norm=Normalize(0.0, 1.0), cmap=cmap)
    sm.set_array(np.linspace(0.0, 1.0, 256))
    cb = fig.colorbar(sm, cax=cax, orientation="horizontal")
    cb.set_ticks([])
    cb.outline.set_visible(False)
    cax.set_xlabel("spectral weight"
                   + (" (log scale)" if weight_scale == "log" else ""),
                   fontsize=8, labelpad=1)
    cax.text(-0.008, 0.5, "Low", transform=cax.transAxes, ha="right",
             va="center", fontsize=9)
    cax.text(1.008, 0.5, "High", transform=cax.transAxes, ha="left",
             va="center", fontsize=9)
    # 高对称点标签: 放在色条**上方**(坐标是主轴的 y 坐标 0~1)
    label_y = (cax.get_position().y1 - pos.y0) / pos.height + 0.012
    for label, d in labels:
        ax.text(float(d), label_y, label, transform=ax.get_xaxis_transform(),
                ha="center", va="bottom", fontsize=9)
    if mirror:
        for label, d in labels:
            ax.text(-float(d), label_y, label,
                    transform=ax.get_xaxis_transform(),
                    ha="center", va="bottom", fontsize=9)
    fig.text(0.5, 0.015, plot_caption(e_f, lo, hi), ha="center", va="bottom",
             fontsize=8)
    return fig, ax


def _band_heatmap_figure(distances: np.ndarray, energies: np.ndarray,
                          weights: np.ndarray, labels: Sequence[Tuple[str, float]],
                          e_f: float, e_min: Optional[float] = None,
                          e_max: Optional[float] = None, mirror: bool = False,
                          weight_scale: str = "linear", sigma: float = 0.06):
    """画**谱函数热图** A(k,E) -> (fig, ax)。

    布局照用户给的参考截图：x = k-path 距离, y = 能量(eV), jet 配色,
    E_F 处一条**白色**虚线, 高对称点标签在 x 轴下面, **底部**一条横向
    colorbar(左 Low 右 High, 无刻度)。

    颜色 = A(k,E) 按 ``weight_scale`` 归一化后的值（与线图同一口径）✓
    """
    _require_matplotlib()
    import matplotlib.pyplot as plt
    from matplotlib.cm import ScalarMappable
    from matplotlib.colors import Normalize

    dist = np.asarray(distances, dtype=float)
    energy = np.atleast_2d(np.asarray(energies, dtype=float))
    weight = np.atleast_2d(np.asarray(weights, dtype=float))
    lo = e_min if e_min is not None else float(np.nanmin(energy))
    hi = e_max if e_max is not None else float(np.nanmax(energy))
    step = max((hi - lo) / 1200.0, 1e-3)
    e_grid = np.arange(lo, hi + 0.5 * step, step)

    fig, ax = plt.subplots(figsize=(6.0, 4.5))
    cmap = plt.get_cmap("jet")
    groups = [(dist, energy, weight)]
    if mirror:
        groups.append(mirror_path(dist, energy, weight))
    for d, e, w in groups:
        A = band_spectral_function(d, e, w, e_grid, sigma)
        scaled = _band_figure_colors(A, weight_scale).reshape(A.shape)
        ax.pcolormesh(d, e_grid, scaled, cmap=cmap, vmin=0.0, vmax=1.0,
                      shading="auto")
    ax.set_ylim(lo, hi)
    x_lo = min(float(np.min(d)) for d, _e, _w in groups)
    x_hi = max(float(np.max(d)) for d, _e, _w in groups)
    ax.set_xlim(x_lo, x_hi)
    if np.isfinite(e_f) and lo <= float(e_f) <= hi:
        ax.axhline(float(e_f), color="w", linestyle="--", linewidth=0.9,
                   zorder=3)
    # 高对称点标签: 在 x 轴**下面**(参考截图的样式)
    for label, d in labels:
        ax.axvline(float(d), color="w", linewidth=0.5, alpha=0.6, zorder=2)
        ax.text(float(d), -0.012, label, transform=ax.get_xaxis_transform(),
                ha="center", va="top", fontsize=9, color="k")
    if mirror:
        for label, d in labels:
            ax.axvline(-float(d), color="w", linewidth=0.5, alpha=0.6, zorder=2)
            ax.text(-float(d), -0.012, label, transform=ax.get_xaxis_transform(),
                    ha="center", va="top", fontsize=9, color="k")
    ax.set_xlabel(K_PATH_AXIS_LABEL)
    ax.set_ylabel("Energy (eV)")
    # 底部横向 colorbar(左 Low 右 High, 无刻度) —— 参考截图的样式
    pos = ax.get_position()
    cax = fig.add_axes([pos.x0 + 0.18 * pos.width, pos.y0 - 0.115,
                         0.64 * pos.width, 0.022])
    sm = ScalarMappable(norm=Normalize(0.0, 1.0), cmap=cmap)
    sm.set_array(np.linspace(0.0, 1.0, 256))
    cb = fig.colorbar(sm, cax=cax, orientation="horizontal")
    cb.set_ticks([])
    cb.outline.set_visible(False)
    cax.text(-0.01, 0.5, "Low", transform=cax.transAxes, ha="right",
             va="center", fontsize=10)
    cax.text(1.01, 0.5, "High", transform=cax.transAxes, ha="left",
             va="center", fontsize=10)
    cax.set_xlabel("spectral weight"
                   + (" (log scale)" if weight_scale == "log" else ""),
                   fontsize=8, labelpad=1)
    fig.text(0.5, 0.015, plot_caption(e_f, lo, hi), ha="center", va="bottom",
             fontsize=8)
    return fig, ax
