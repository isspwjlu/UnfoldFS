"""展开能带(unfolded band structure): KPATH.in -> 超胞 k -> 展开 -> vaspkit 四件套。

**这一模块的产物是给用户组现有的 MATLAB 脚本用的**:
``/data/wjlu/work/vasp_work/TaS2_new/AH_sliding_1v6/unfolded_band/
unfold_band_plot_mirror.m`` 读 ``ENERGY.grd`` / ``MOMENTUM.grd`` / ``WEIGHT.grd`` /
``KLABELS`` 画 E-vs-k 的加权能带图 ⇒ **文件名与布局必须与 vaspkit 完全一致**,
那个脚本才能不改一行直接画我们的数据。

布局(服务器实测 2026-11-18, 与 MATLAB 脚本的 ``pcolor(momentum, energy, weight)``
用法一致):

  * 三个 .grd 是**同样大小**的矩阵, **列 = 路径上的 k 点, 行 = 带**;
  * ``MOMENTUM.grd`` 的每一行都是同一条"沿路径的累计距离"序列;
  * ``ENERGY.grd`` 存**绝对能量**(eV, 与 vaspkit 一致 —— MATLAB 脚本用
    ``Efermi_adjust`` 自己把费米能平移到 0);
  * ``WEIGHT.grd`` 存该带在该 k 点的权重;
  * 数值字段宽度 **14**("%%14.6f"), 与 vaspkit 的 .grd 逐字节同格式;
  * ``KLABELS`` = 表头 + N 行"标签 + 距离"(标签**右对齐**在 12 列, 距离右对齐在
    12 列)+ 2 行只含一个空格 + vaspkit 的提示行。

**权重语义(必须与 vaspkit 282 区分开)**: 这里的权重是 **Popescu 投影法给出的
G 分辨权重**(路径点上取"原胞 k 等于该路径点"的那个候选的投影权重),
**不是** vaspkit 282 用 WAVECAR 平面波展开得到的原胞带 |c(k)|²。两者都叫
"权重"但物理含义不同 ⇒ 见 docs/algorithms.md 的对应一节。

⚠ **已知限制(必须一并披露)**: 展开谱权重在晶体点群下**不协变**(实测最大相对偏差
MoS₂ 9.186e-01 / 1T-TaS₂ 1.000e+00), 而**带能量不受影响**(对称相关点吻合到
8e-6 eV) ⇒ **能带曲线可信, 能带的"形状/对称性"不可信**。

⇒ **修复轮 5**: ``symmetrize_band_weights`` 把路径上**对称相关**的点的权重按
点群轨道平均(默认开启, ``--no-symmetrize`` 可关)。但它**只动权重**、且
**只在路径上存在对称相关点时**才生效(泛路径点的轨道离开路径) ⇒ 见
docs/algorithms.md §16.7。

⇒ **修复轮 6**: 轨道平均用的是**原胞完整点群**(不是"原胞与超胞的公共对称
操作")—— 破坏对称性的超胞只保留 4/12 个公共操作, 用公共子群会漏掉路径上
其余的对称相关点。见 docs/algorithms.md §15.8。
"""
