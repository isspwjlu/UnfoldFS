"""展开能带(unfolded band)的测试: KPATH.in 解析 -> 超胞 k -> 展开 -> vaspkit 四件套。

**为什么格式测试照抄服务器实测的样例**: 用户组的 MATLAB 脚本
``unfold_band_plot_mirror.m`` 按 vaspkit 的布局读 ``ENERGY.grd`` /
``MOMENTUM.grd`` / ``WEIGHT.grd`` / ``KLABELS`` —— 文件名与布局必须一模一样,
否则那个脚本画不出图。故本文件里的 KPATH.in / KLABELS 样例都是**服务器实测**
(2026-11-18, $WORKDIR/vasp_work/TaS2_new/AH_sliding_1v6/unfolded_band)
逐字节照抄的, 不做任何"美化"。

**MATLAB 侧的解析口径**(读 unfold_band_plot_mirror.m 得到):
  * KLABELS: 第 1 行是表头, 随后 ``Nline-4`` 行是"标签 + 距离",
    再 2 行只含一个空格, 最后一行是 vaspkit 的提示;
    每行用 ``regexp(str, '\\s+', 'split')`` 切成 S(1)='' S(2)=标签 S(3)=距离
    ⇒ **标签必须右对齐(前面有空白)**, 否则 S(2) 会变成距离;
  * 三个 .grd 是同样大小的矩阵, ``pcolor(momentum, energy, weight)``:
    **列 = 路径上的 k 点, 行 = 带**; momentum 的每一行都是同一条距离序列。
"""
import os
import pathlib
import re

import numpy as np
import pytest

from unfoldfs import band, cli

# ------------------------------------------------------------------ 样例

# 服务器实测的 vaspkit KPATH.in(逐字节照抄)
KPATH_VASPKIT = """K-Path Generated by VASPKIT.
   30
Line-Mode
Reciprocal
 0.5000000000   0.0000000000   0.0000000000     M
 0.0000000000   0.0000000000   0.0000000000     GAMMA

 0.0000000000   0.0000000000   0.0000000000     GAMMA
 0.5000000000   0.0000000000   0.0000000000     M

 0.0000000000   0.0000000000   0.0000000000     GAMMA
 0.0000000000   0.0000000000   0.5000000000     A

"""

# 服务器实测的 KLABELS(结构与缩进都照抄; 距离值随晶格而变, 这里只查结构)
KLABELS_HEADER = ("K-Label    Coordinate of high-symmetry k-point in "
                   "band-structure plots ")
KLABELS_TIP = ("* Tip: Please label each high symmetry point in KPOINTS "
               "(KPATH.in) file. Otherwise, they will be identified as 'XX' "
               "in KLABELS file")


def _write(path, text):
    pathlib.Path(path).write_text(text, encoding="utf-8")
    return str(path)


def _matlab_klabels(path):
    """按 MATLAB 脚本的口径解析 KLABELS -> [(标签, 距离), ...]。"""
    lines = pathlib.Path(path).read_text(encoding="utf-8").splitlines()
    out = []
    for line in lines[1:len(lines) - 3]:
        # MATLAB: S = regexp(str, '\s+', 'split'); 用 S(2)=标签 S(3)=距离
        parts = re.split(r"\s+", line)
        assert parts[0] == "", f"标签行必须以空白开头(MATLAB 的 S(2) 才是标签): {line!r}"
        out.append((parts[1], float(parts[2])))
    return out


# ------------------------------------------------------------------ KPATH.in

def test_read_kpath_parses_vaspkit_segments(tmp_path):
    p = _write(tmp_path / "KPATH.in", KPATH_VASPKIT)
    path = band.read_kpath(p)
    assert len(path.segments) == 3
    assert path.n_points_per_segment == 30
    assert path.segments[0].start_label == "M"
    assert path.segments[0].end_label == "GAMMA"
    assert path.segments[1].start_label == "GAMMA"
    assert path.segments[1].end_label == "M"
    assert path.segments[2].start_label == "GAMMA"
    assert path.segments[2].end_label == "A"
    np.testing.assert_allclose(path.segments[0].start, [0.5, 0.0, 0.0])
    np.testing.assert_allclose(path.segments[2].end, [0.0, 0.0, 0.5])


def test_read_kpath_samples_each_segment_with_both_endpoints(tmp_path):
    """每段采 n 个点(含两端); 段与段的交界点出现两次(与 vaspkit 一致)。

    vaspkit 实测: 3 段 x 30 点 -> KPOINTS 里 90 个 k 点, MOMENTUM.grd 的
    距离序列里交界点的距离值出现两次(132 列里只有 130 个不同的值)。
    """
    p = _write(tmp_path / "KPATH.in", KPATH_VASPKIT)
    path = band.read_kpath(p)
    assert path.k_prim.shape == (90, 3)
    # 第一段的起点与终点
    np.testing.assert_allclose(path.k_prim[0], [0.5, 0.0, 0.0])
    np.testing.assert_allclose(path.k_prim[29], [0.0, 0.0, 0.0])
    # 第二段从交界点重新开始 -> 交界点出现两次
    np.testing.assert_allclose(path.k_prim[30], [0.0, 0.0, 0.0])
    np.testing.assert_allclose(path.k_prim[59], [0.5, 0.0, 0.0])
    np.testing.assert_allclose(path.k_prim[60], [0.0, 0.0, 0.0])
    np.testing.assert_allclose(path.k_prim[-1], [0.0, 0.0, 0.5])


def test_path_labels_follow_the_vaspkit_junction_convention(tmp_path):
    """高对称点的标签表: 交界点写成"前一段的终点|后一段的起点"。

    服务器实测的 KLABELS(3 段 M->GAMMA, GAMMA->M, GAMMA->A)正是:
        M / GAMMA / M|GAMMA / A
    ⇒ 段内两端同名时只写一次, 不同名时写 "end|start"。
    """
    p = _write(tmp_path / "KPATH.in", KPATH_VASPKIT)
    path = band.read_kpath(p)
    b_prim = np.diag([2.0, 2.0, 2.0])
    dist = band.path_distances(path, b_prim)
    labels = band.path_labels(path, dist)
    assert [lab for lab, _ in labels] == ["M", "GAMMA", "M|GAMMA", "A"]
    # 距离取自路径上对应的点(交界点用前一段的末点)
    assert labels[0][1] == pytest.approx(dist[0])
    assert labels[1][1] == pytest.approx(dist[29])
    assert labels[2][1] == pytest.approx(dist[59])
    assert labels[3][1] == pytest.approx(dist[-1])


def test_path_labels_of_a_single_segment_have_two_entries(tmp_path):
    p = _write(tmp_path / "KPATH.in", """K-Path Generated by VASPKIT.
   10
Line-Mode
Reciprocal
 0.0000000000   0.0000000000   0.0000000000     GAMMA
 0.0000000000   0.0000000000   0.5000000000     A
""")
