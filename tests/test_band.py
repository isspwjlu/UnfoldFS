def test_path_distances_are_cumulative_and_monotone(tmp_path):
    p = _write(tmp_path / "KPATH.in", KPATH_VASPKIT)
    path = band.read_kpath(p)
    b_prim = np.diag([2.0, 2.0, 2.0])
    dist = band.path_distances(path, b_prim)
    assert dist.shape == (90,)
    assert dist[0] == 0.0
    assert np.all(np.diff(dist) >= -1e-12)
    # 交界点上距离不增加(交界点出现两次)
    assert dist[29] == pytest.approx(dist[30])
    # 第一段: M(0.5,0,0) -> GAMMA, 长度 = |0.5 * b1|
    assert dist[29] == pytest.approx(0.5 * np.linalg.norm(b_prim[0]))


