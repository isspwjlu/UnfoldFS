_A_PRIM = np.diag([3.0, 4.0, 5.0])
_M = np.diag([3, 1, 1])
_PRIM_FRAC = np.array([[0.0, 0.0, 0.0], [0.5, 0.5, 0.5]])
_BAND_ENERGIES = (-10.0, -6.0, -2.0, 1.0, 3.0, 5.0)
_DOS_EF = -3.0
_U = np.array([0.1027125684732821 - 0.21014635803702303j,
                0.23240310131893024 - 0.7116491117596169j,
                0.5501292501189036 + 1.001533391119041j])
_THETA = (0.0, np.pi / 4, np.pi / 2, 3 * np.pi / 4, np.pi, 5 * np.pi / 4)

# 路径: 原胞 k 从 0 到 0.75 沿 a 方向, 8 个采样点。
# **点数刻意与带数不同**(8 != 展开后的带数)—— 否则 (n_band, n_k) 矩阵是方的,
# 转置了也看不出(变异自检 M3 就曾这样漏网)。
_PATH_K = [(0.75 * i / 7.0, 0.0, 0.0) for i in range(8)]
KPATH_SIMPLE = """K-Path Generated by VASPKIT.
    8
Line-Mode
Reciprocal
 0.0000000000   0.0000000000   0.0000000000     GAMMA
 0.7500000000   0.0000000000   0.0000000000     M
"""


def _write_poscar(path, title, lattice, frac, species, counts):
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(title + "\n")
        fh.write("   1.000000000000000\n")
        for row in lattice:
            fh.write("  %22.16f %22.16f %22.16f\n" % tuple(row))
        fh.write("  " + " ".join(species) + "\n")
        fh.write("  " + " ".join(str(c) for c in counts) + "\n")
        fh.write("Direct\n")
        for p in frac:
            fh.write("  %22.16f %22.16f %22.16f\n" % tuple(p))


def _write_band_system(directory, k_super):
    """写出一个自洽的迷你 VASP 计算目录(k 点 = 展开路径的超胞 k)。"""
    os.makedirs(directory, exist_ok=True)
    n_band = len(_BAND_ENERGIES)
    a_sc = _M @ _A_PRIM
    frac = []
    for p in _PRIM_FRAC @ _A_PRIM:
        for j in range(3):
            frac.append((p + j * _A_PRIM[0]) @ np.linalg.inv(a_sc))
    _write_poscar(os.path.join(directory, "POSCAR"), "synthetic supercell",
                  a_sc, frac, ["Si"], [6])
    _write_poscar(os.path.join(directory, "PRIMCELL.vasp"), "synthetic prim",
                  _A_PRIM, _PRIM_FRAC, ["Si"], [2])
    with open(os.path.join(directory, "TRANSMAT.in"), "w",
              encoding="utf-8") as fh:
        fh.write("  3  0  0\n  0  1  0\n  0  0  1\n")
    with open(os.path.join(directory, "EIGENVAL"), "w",
              encoding="utf-8") as fh:
        fh.write("   6   6    1    1\n")
        fh.write("  1.0E+02  0.0E+00  0.0E+00  0.1E-08  0.5E-15\n")
        fh.write("  1.0E-04\n  CAR \n synthetic\n")
        fh.write("    2      %d    %d\n" % (len(k_super), n_band))
        fh.write("\n")
        for ik, kfrac in enumerate(k_super):
            fh.write("  %14.7E %14.7E %14.7E %14.7E\n"
                     % (kfrac[0], kfrac[1], kfrac[2], 1.0))
            for b, e in enumerate(_BAND_ENERGIES):
                fh.write("  %5d %14.6f %10.6f\n"
                         % (b + 1, e - 0.1 * ik, 1.0 if b < 2 else 0.0))
            fh.write("\n")
    with open(os.path.join(directory, "DOSCAR"), "w", encoding="utf-8") as fh:
        fh.write("   6   6   1   0\n")
        fh.write("  1.0E+02  0.0E+00  0.0E+00  0.1E-08  0.5E-15\n")
        fh.write("  1.0E-04\n  CAR \n synthetic\n")
        fh.write("  1.0E+01 -1.0E+01  301  %20.10E  1.0E+00\n" % _DOS_EF)
        for i in range(301):
            fh.write("  %14.6f 0.0000E+00 0.0000E+00\n"
                     % (-10.0 + i * 20.0 / 300.0))
    coeffs = np.zeros((n_band, 6, 1), dtype=complex)
    for b, theta in enumerate(_THETA[:n_band]):
        at = np.array([1.0 + 0j, np.exp(1j * theta)])
        for i in range(2):
            for j in range(3):
                coeffs[b, i * 3 + j, 0] = at[i] * _U[j]
    with open(os.path.join(directory, "PROCAR"), "w", encoding="utf-8") as fh:
        fh.write("PROCAR lm decomposed + phase\n")
        fh.write("# of k-points: %3d         # of bands:  %d"
                 "         # of ions:    6\n" % (len(k_super), n_band))
        fh.write("\n")
        for ik, kfrac in enumerate(k_super):
            fh.write(" k-point %5d :    %.8f %.8f %.8f"
                     "     weight = 1.00000000\n"
                     % (ik + 1, kfrac[0], kfrac[1], kfrac[2]))
            for b in range(n_band):
                fh.write("\n")
                fh.write("band  %5d # energy  %14.8f # occ.  1.00000000\n"
                         % (b + 1, _BAND_ENERGIES[b] - 0.1 * ik))
                fh.write("\n")
                fh.write("ion      s     tot\n")
                tot = 0.0
                for i in range(6):
                    m2 = abs(coeffs[b, i, 0]) ** 2
                    tot += m2
                    fh.write("  %3d  %12.8f  %12.8f\n" % (i + 1, m2, m2))
                fh.write("tot   %12.8f  %12.8f\n" % (tot, tot))
                fh.write("ion      s\n")
                for i in range(6):
                    c = coeffs[b, i, 0]
                    fh.write("  %3d %14.8f %14.8f %14.8f\n"
                             % (i + 1, c.real, c.imag, abs(c) ** 2))


def _super_k_of_path():
    """路径原胞 k -> 超胞 k(mod 1)。"""
    k_prim = np.array(_PATH_K)
    return np.mod(k_prim @ _M.T, 1.0)


