def test_write_kpoints_explicit_uses_a_comment_first_line(tmp_path):
    """首行必须是纯注释: VASP 按首行第一个字符选分支, 'G'/'M' 会走自动网格。"""
    out = str(tmp_path / "KPOINTS")
    k_super = np.array([[0.0, 0.0, 0.0], [0.25, 0.0, 0.0], [0.5, 0.0, 0.0]])
    band.write_kpoints_explicit(out, k_super)
    lines = pathlib.Path(out).read_text(encoding="utf-8").splitlines()
    assert lines[0][0] not in "GgMmKkSsCcRr"
    assert lines[0].lower().startswith("unfoldfs")
    assert int(lines[1].split()[0]) == 3
    assert lines[2].strip() == "Reciprocal lattice"
    rows = [ln.split() for ln in lines[3:]]
    assert len(rows) == 3                       # 行数 == 路径点数
    for row, k in zip(rows, k_super):
        assert len(row) == 4
        np.testing.assert_allclose([float(x) for x in row[:3]], k, atol=1e-12)


