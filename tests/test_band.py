def _fake_unfolded(n_k=3, n_band=2, n_cand=3):
    """构造一个 UnfoldedResult 替身(只带 assemble_band 用到的字段)。"""
    class _R:
        pass
    r = _R()
    r.k_cand = np.zeros((n_k, n_cand, 3))
    for i in range(n_k):
        for j in range(n_cand):
            r.k_cand[i, j] = [j / n_cand, 0.0, 0.0]
    r.energies = np.full((n_k, n_cand, n_band), np.inf)
    r.weights = np.zeros((n_k, n_cand, n_band))
    r.valid = np.zeros((n_k, n_cand, n_band), dtype=bool)
    for i in range(n_k):
        # 第 i 个 k 点的匹配候选就是第 i 个(k_cand[i, i] = [i/n_cand, 0, 0])
        r.energies[i, i, 0] = -1.0 - i
        r.weights[i, i, 0] = 0.9
        r.valid[i, i, 0] = True
        r.energies[i, i, 1] = 2.0 + i
        r.weights[i, i, 1] = 0.4
        r.valid[i, i, 1] = True
    return r


def test_assemble_band_takes_the_zero_candidate_of_every_k_point():
    r = _fake_unfolded()
    k_prim = np.array([[0.0, 0.0, 0.0], [1.0 / 3, 0.0, 0.0], [2.0 / 3, 0.0, 0.0]])
    energy, weight = band.assemble_band(r, k_prim)
    assert energy.shape == (2, 3)
    np.testing.assert_allclose(energy[0], [-1.0, -2.0, -3.0])
    np.testing.assert_allclose(weight[0], [0.9, 0.9, 0.9])


def test_assemble_band_pads_missing_bands_with_zero_weight():
    """某个 k 点的候选带数少时, 多出来的行用"该 k 的最高带能量 + 权重 0"补位。"""
    r = _fake_unfolded()
    # 第 2 个 k 点只有一条带
    r.energies[1, 1, 1] = np.inf
    r.weights[1, 1, 1] = 0.0
    r.valid[1, 1, 1] = False
    k_prim = np.array([[0.0, 0.0, 0.0], [1.0 / 3, 0.0, 0.0], [2.0 / 3, 0.0, 0.0]])
    energy, weight = band.assemble_band(r, k_prim)
    assert energy.shape == (2, 3)
    assert weight[1, 1] == 0.0
    assert np.isfinite(energy[1, 1])
    assert energy[1, 1] == pytest.approx(energy[0, 1])


def test_assemble_band_raises_when_a_k_point_has_no_candidate():
    r = _fake_unfolded(n_k=1)
    k_prim = np.array([[0.5, 0.0, 0.0]])
