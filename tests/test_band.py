    res = U.UnfoldedResult(k_cand=k_cand, energies=energies, weights=weights,
                            valid=valid)
    e, w = band.assemble_band(res, np.array([[0.0, 0.0, 0.0]]),
                              mode="assign")
    assert e.shape == (2, 1)          # 只有归属到候选 0 的两条
    assert list(e[:, 0]) == [1.0, 2.0]


