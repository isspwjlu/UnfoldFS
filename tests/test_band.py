# ------------------------------------------------------------------ 路径 -> 超胞 k

def test_super_from_prim_uses_the_transposed_transform(tmp_path):
    """K = k'·Mᵀ (mod 1) —— 转置错了结果就不同(非对角 M 时尤其明显)。"""
    m = np.array([[2, 1, 0], [0, 1, 0], [0, 0, 1]])
    k_prim = np.array([0.3, 0.2, 0.1])
    expected = np.mod(k_prim @ m.T, 1.0)
    wrong = np.mod(k_prim @ m, 1.0)
    assert not np.allclose(expected, wrong)      # 这个 M 能区分两种写法
    got = band.path_to_super_k(k_prim, m)
    np.testing.assert_allclose(got, expected)
    # 与 geometry.Transform 的约定一致
    from unfoldfs.geometry import Transform
    tr = Transform(m, np.linalg.inv(m.astype(float)))
    np.testing.assert_allclose(got, tr.super_from_prim(k_prim))


def test_path_to_super_k_of_the_whole_path(tmp_path):
    p = _write(tmp_path / "KPATH.in", KPATH_VASPKIT)
    path = band.read_kpath(p)
    m = np.diag([3, 1, 1])
    k_super = band.path_to_super_k(path.k_prim, m)
    assert k_super.shape == (90, 3)
    np.testing.assert_allclose(k_super[0], np.mod([0.5, 0, 0] @ m.T, 1.0))
    assert np.all(k_super >= 0.0) and np.all(k_super < 1.0)


