    assert p_cb.y0 > p_ax.y1, "色条必须画在主坐标区上方"
    assert abs(p_cb.width - p_ax.width) < 0.02, "色条应与主坐标区同宽"
    assert p_cb.height < 0.08 and p_cb.width > 0.3, "色条应是横向的细条"


