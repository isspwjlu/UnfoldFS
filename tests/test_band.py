def test_band_prepare_writes_kpoints_incar_and_klabels(tmp_path):
    run = tmp_path / "run"
    _write_band_system(str(run), _super_k_of_path())
    kpath = _write(tmp_path / "KPATH.in", KPATH_SIMPLE)
    rc = cli.main(["band",
                   "--supercell", os.path.join(str(run), "POSCAR"),
                   "--primcell", os.path.join(str(run), "PRIMCELL.vasp"),
                   "--transmat", os.path.join(str(run), "TRANSMAT.in"),
                   "--kpath", kpath,
                   "--outdir", str(run)])
    assert rc == 0
    assert (run / "KPOINTS").is_file()
    assert (run / "INCAR.suggested").is_file()
    assert (run / "KLABELS.in").is_file()
    assert (run / "KPATH.in").is_file()
    incar = (run / "INCAR.suggested").read_text(encoding="utf-8")
    tags = {}
    for line in incar.splitlines():
        s = line.strip()
        if not s or s.startswith("#") or "=" not in s:
            continue
        tag, _, value = s.partition("=")
        tags[tag.strip().upper()] = value.strip()
    assert tags["ISYM"] == "0"
    assert tags["LORBIT"] == "12"
    # KPOINTS 的 k 点必须就是路径点的超胞坐标
    lines = (run / "KPOINTS").read_text(encoding="utf-8").splitlines()
    n = int(lines[1].split()[0])
    assert n == len(_PATH_K)
    got = np.array([[float(x) for x in ln.split()[:3]] for ln in lines[3:3 + n]])
    np.testing.assert_allclose(got, _super_k_of_path(), atol=1e-9)


